// ── 이상한 값 막기 ──
//    설문에서 칸을 비우면 0 이나 NaN 이 들어옵니다. 그대로 계산하면
//    화면에 Infinity · NaN 이 그대로 찍힙니다. 아래에서 미리 걸러냅니다.
const 기본기간주 = 12;

function 숫자로(값, 기본){
  const n = Number(값);
  return Number.isFinite(n) ? n : 기본;
}


// ── 하루 목표 칼로리 ──
//    계산식 자체는 그대로입니다. 0으로 나누는 것만 막았습니다.
function 기준값계산(프로필){
  const p = 프로필 || {};
  const 현재체중 = 숫자로(p.현재체중, 0);
  const 목표체중 = 숫자로(p.목표체중, 현재체중);
  let  기간주   = 숫자로(p.기간주, 기본기간주);
  if(기간주 <= 0) 기간주 = 기본기간주;      // ★ 0주 · 음수 → 12주로 본다 (0으로 안 나눔)

  const 유지     = 현재체중 * 30;
  const 총감량   = 현재체중 - 목표체중;
  const 하루적자 = (총감량 * 7700) / (기간주 * 7);

  let 목표kcal = Math.round(유지 - 하루적자);
  if(!Number.isFinite(목표kcal)) 목표kcal = 1200;      // ★ Infinity · NaN 이면 하한으로
  목표kcal = Math.max(1200, 목표kcal);                 //   1200 밑으로는 안 내려감

  let 목표단백질 = Math.round(목표체중 * 1.2);
  if(!Number.isFinite(목표단백질) || 목표단백질 < 30) 목표단백질 = 30;

  return { 목표kcal, 목표단백질 };
}


// ── 목표가 안전한지 ── 일주일에 몸무게의 1%까지만 허용
function 목표안전한가(프로필){
  if(프로필.목표체중 >= 프로필.현재체중) return { ok:true };
  const 주당 = (프로필.현재체중 - 프로필.목표체중) / 프로필.기간주;
  const 상한 = 프로필.현재체중 * 0.01;
  if(주당 > 상한){
    const 필요주 = Math.ceil((프로필.현재체중 - 프로필.목표체중) / 상한);
    return { ok:false, 메시지:"그 속도는 몸에 무리예요. 같은 목표를 " + 필요주 + "주로 잡으면 안전해요." };
  }
  return { ok:true };
}


