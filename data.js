//    ★ 이름이 긴 것을 먼저 고릅니다.
//      예전에는 표를 위에서부터 훑다가 처음 걸리는 걸 돌려줬습니다. 그래서
//      "참치김밥 먹었어" 가 표에 먼저 있는 "김밥" 으로 기록됐습니다.
//      이제 "참치김밥"(4글자)이 "김밥"(2글자)을 이깁니다.
//    못 찾으면 null. 지어내지 않습니다.
function 음식찾기(글){
  const 글자 = String(글 || "");
  let 찾은 = null;
  let 맞춘길이 = 0;      // 몇 글자짜리 말에 걸렸는지 — 긴 쪽이 이깁니다

  for(const 음식 of 음식표){
    for(const 낱말 of [음식.이름, ...(음식.별명 || [])]){
      if(!글자.includes(낱말)) continue;
      if(낱말.length > 맞춘길이){ 찾은 = 음식; 맞춘길이 = 낱말.length; }
    }
  }
  return 찾은;
}


