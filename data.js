// ── 기준 좌표 정하기 ──
//    위치글을 적었으면 그 근처. 비워두면 브라우저에 지금 어디냐고 물어봅니다.
function 내위치받기(){
  return new Promise((성공, 실패) => {
    if(typeof navigator === "undefined" || !navigator.geolocation){
      실패(new Error("이 브라우저는 위치를 알려주지 못합니다")); return;
    }
    navigator.geolocation.getCurrentPosition(
      p => 성공({ 위도:p.coords.latitude, 경도:p.coords.longitude }),
      () => 실패(new Error("위치 사용을 허락해야 현재 위치로 찾을 수 있습니다")),
      { timeout:10000, maximumAge:60000 }
    );
  });
}

async function 기준좌표(위치글){
  const 글 = String(위치글 || "").trim();
  if(글 && 글 !== "현재위치"){
    const 결과 = await 장소검색(글);
    if(!결과.length) throw new Error("\"" + 글 + "\" 을(를) 카카오에서 못 찾았습니다");
    return new window.kakao.maps.LatLng(Number(결과[0].y), Number(결과[0].x));
  }
  await 카카오준비하기();
  const 여기 = await 내위치받기();
  return new window.kakao.maps.LatLng(여기.위도, 여기.경도);
}


/* ── 근처식당찾기(위치글) ──
   그 위치 500m 안에서, 우리가 아는 종류의 가게만 골라 식당표 모양으로 만듭니다.

   찾는 방법:
     1) 종류별 낱말로 따로따로 검색 — 45곳 제한을 피하려는 것 (위 설명 참고)
     2) 그 위에 "음식점 전체 / 편의점 전체" 도 한 번씩 훑어 빠진 걸 줍습니다
     3) 카카오가 준 분류로 메뉴·영양·알레르기를 붙입니다
     4) 모르는 분류는 버립니다 — "모르면 추천 안 함" */
async function 근처식당찾기(위치글){
  const 중심 = await 기준좌표(위치글);

  // 한꺼번에 다 부르면 카카오가 거절할 수 있어 6개씩 나눠 부릅니다.
  const 후보 = [];
  for(let i = 0; i < 검색어목록.length; i += 6){
    const 묶음 = await Promise.all(
      검색어목록.slice(i, i + 6).map(낱말 => 낱말로찾기(낱말, 중심, 찾을반경))
    );
    묶음.forEach(목록 => 후보.push(...목록));
  }

  // 종류 낱말로 안 걸린 가게를 줍기 위해 전체도 한 번 훑습니다.
  for(const 코드 of ["FD6", "CS2"]){
    try{ 후보.push(...await 카테고리검색(코드, 중심, 찾을반경)); }
    catch(e){ /* 실패해도 위 결과로 갑니다 */ }
  }

  // 같은 가게가 여러 낱말에 걸립니다. 한 번만 남기고 가까운 순으로 세웁니다.
  const 본것 = new Set();
  const 정리된 = 후보
    .filter(g => {
      const 표 = g.id || (g.place_name + "|" + g.distance);
      if(본것.has(표)) return false;
      본것.add(표);
      return true;
    })
    .sort((a,b) => Number(a.distance) - Number(b.distance));

  const 나온것 = [];
  const 메뉴본것 = {};

  for(const g of 정리된){
    const 미터 = Math.round(Number(g.distance));
    if(!Number.isFinite(미터) || 미터 > 찾을반경) continue;   // 반경 밖은 버립니다
    if(회사이름.some(w => g.place_name.includes(w))) continue;

    const 규칙 = 분류로메뉴찾기(g.category_name);
    if(!규칙) continue;                       // ★ 모르는 종류는 추천 안 함

    const [, 메뉴, kcal, 단백질, 들어간것] = 규칙;

    // 같은 메뉴는 가장 가까운 한 곳만. 안 그러면 추천 3개가 전부 치킨집이 됩니다.
    if(메뉴본것[메뉴]) continue;
    메뉴본것[메뉴] = true;

    나온것.push({
      가게: g.place_name,
      메뉴: 메뉴,
      거리: 미터,
      kcal: kcal,
      단백질: 단백질,
      들어간것: [...들어간것],
      지도: g.place_url
    });
  }
  return 나온것;
}


/* ── 주변갱신(위치글) ── ★ B 가 부르는 것
   식당표를 그 동네 것으로 갈아 끼웁니다.

   B 에게 — 설문을 저장한 뒤 이 한 줄이면 됩니다:
       주변갱신(상태.프로필.위치).catch(()=>{});
   실패해도 아무 일도 안 일어납니다. 표가 강남역 것으로 남을 뿐입니다. */
async function 주변갱신(위치글){
  let 새목록 = [];
  try{
    새목록 = await 근처식당찾기(위치글);
  }catch(e){
    return { 바뀜:false, 곳:식당표.length, 까닭:e.message };
  }

  if(!새목록.length){
    return { 바뀜:false, 곳:식당표.length, 까닭:"근처에서 추천할 만한 가게를 못 찾았습니다" };
  }

  식당표.length = 0;              // 배열 속만 비웁니다. 이름은 그대로라 다른 파일이 안 깨집니다.
  식당표.push(...새목록);
  return { 바뀜:true, 곳:식당표.length };
}


// ── 처음 표로 되돌리기 ── 검색이 이상할 때 쓸 수 있게 남겨둡니다.
function 식당표되돌리기(){
  식당표.length = 0;
  식당표.push(...처음식당표.map(m => ({ ...m, 들어간것:[...m.들어간것] })));
  return 식당표.length;
}


// ── 지도링크(메뉴) ── 추천 카드에 "지도 보기"를 붙이고 싶을 때 씁니다.
function 지도링크(메뉴){
  const 가게 = 식당표.find(x => x.메뉴 === 메뉴);
  return (가게 && 가게.지도) || null;
}


