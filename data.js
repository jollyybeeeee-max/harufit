// ── 하루 목표 칼로리 ──
//    지금은 아주 단순한 식입니다. C가 제대로 된 공식으로 바꾸세요.
function 기준값계산(프로필){
  const 유지 = 프로필.현재체중 * 30;
  const 총감량 = 프로필.현재체중 - 프로필.목표체중;
  const 하루적자 = (총감량 * 7700) / (프로필.기간주 * 7);
  return {
    목표kcal   : Math.max(1200, Math.round(유지 - 하루적자)),  // 1200 밑으로는 안 내려감
    목표단백질 : Math.round(프로필.목표체중 * 1.2)
  };
}


// ── 목표가 안전한지 ── 일주일에 몸무게의 1%까지만 허용
function 목표안전한가(프로필){
  if(프로필.목표체중 >= 프로필.현재체중) return { ok:true };
  const 주당 = (프로필.현재체중 - 프로필.목표체중) / 프로필.기간주;
  const 상한 = 프로필.현재체중 * 0.01;
  if(주당 > 상한){
    const 필요주 = Math.ceil((프로필.현재체중 - 프로필.목표체중) / 상한);
    return { ok:false, 메시지:"그 속도는 몸에 무리예요. 같은 목표를 " + 필요주 + "주로 잡으면 안전해요." };
  }
  return { ok:true };
}


// ── 한 줄 글에서 음식 찾기 ──
//    지금은 글자 맞추기. 못 찾으면 null 을 돌려줍니다. 지어내지 않습니다.
function 음식찾기(글){
  for(const 음식 of 음식표){
    if(글.includes(음식.이름)) return 음식;
  }
  return null;
}
