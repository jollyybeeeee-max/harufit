/* ─────────── 0. 맥락 매칭 ───────────
   글자 하나(부분일치)로 판단하지 않기 위한 도우미.
   낱말이 문장에 있어도 "안 ~", "~지 않", "~ 아니", "~ 없" 같은 부정 맥락이면 매치로 안 친다.
   낱말이 여러 번 나오면, 한 번이라도 "부정 아닌" 자리에 있으면 매치(참)로 본다. */
function 긍정매치(글, 낱말){
  let i = 글.indexOf(낱말);
  while(i !== -1){
    const 앞 = 글.slice(Math.max(0, i - 4), i);
    const 뒤 = 글.slice(i + 낱말.length, i + 낱말.length + 6);
    const 앞부정 = /(안|못|덜)\s*$/.test(앞);
    const 뒤부정 = /^\s*((은|는|이|가|것|건|게)?\s*아니|지\s*않|진\s*않|지\s*못|지\s*마|지\s*말|(은|는|이|가)?\s*없|기\s*싫|안\s*하|안\s*했|안\s*해|끝났|끝나|끝냈)/.test(뒤);
    if(!앞부정 && !뒤부정) return true;      // 긍정 맥락 한 번이라도 있으면 매치
    i = 글.indexOf(낱말, i + 1);
  }
  return false;                              // 없거나, 전부 부정 맥락
}

/* 여러 낱말 중 하나라도 긍정 맥락으로 나오면 참 */
function 어느하나(글, 낱말들){ return 낱말들.some(w => 긍정매치(글, w)); }


