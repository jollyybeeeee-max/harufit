function 조사(단어, 받침있을때, 받침없을때){
  const 글 = String(단어);
  const 끝 = 글.charCodeAt(글.length - 1);
  if(끝 < 0xAC00 || 끝 > 0xD7A3) return 글 + 받침없을때;
  const 종성 = (끝 - 0xAC00) % 28;
  if(종성 === 8 && 받침있을때 === "으로") return 글 + "로";
  return 글 + (종성 ? 받침있을때 : 받침없을때);
}

