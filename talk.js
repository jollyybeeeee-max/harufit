function 규칙으로답하기(글, 프로필, 오늘){
  const 말투체 = (프로필.말투체 === "존댓말") ? "존댓말" : "반말";

  // 컨디션 — "좋음/피곤" 같은 글자 하나가 아니라 자연스러운 표현 + 부정 맥락으로 판단
  //   ("컨디션 안 좋아" → 피곤 / "안 피곤해" → 컨디션 아님)
  const 컨디션 =
      어느하나(글, ["피곤","지쳐","지친","힘들","졸려","기운 없","녹초","뻐근"])   ? "피곤"
    : (긍정매치(글,"안 좋") || 어느하나(글, ["별로","최악","죽겠"]))              ? "피곤"
    : 어느하나(글, ["좋아","좋음","좋다","개운","쌩쌩","가뿐","괜찮","힘 나"])     ? "좋음"
    : 어느하나(글, ["보통","그냥 그래","그저 그래","무난"])                       ? "보통"
    : null;

  // 일정 — 부정("야근 아니야", "약속 없어")이면 잡지 않는다
  const 일정 = 긍정매치(글, "야근") ? "야근"
             : 긍정매치(글, "약속") ? "약속"
             : 긍정매치(글, "평범") ? "평범" : null;

  const 음식 = 음식찾기(글);
  if(음식){
    return { 종류:"음식", 음식:[{이름:음식.이름, kcal:음식.kcal, 단백질:음식.단백질}],
             컨디션, 일정,
             답: 캐릭터문장(프로필, "기록", {메뉴:음식.이름, kcal:음식.kcal}) };
  }

  if(글.includes("?") || 글.includes("뭐") || 글.includes("어때") || 글.includes("할까")){
    // 운동 관련 질문이면 고정 문구 대신 사용자 운동수준·종목을 반영해 답한다
    if(/운동|헬스|스트레칭|요가|러닝|필라테스|홈트/.test(글)){
      return { 종류:"질문", 음식:[], 컨디션, 일정, 답: 운동답(프로필) };
    }
    const 찾은 = 준비된답.find(q => q.키워드.some(k => 글.includes(k)));
    return { 종류:"질문", 음식:[], 컨디션, 일정,
             답: 찾은 ? 찾은[말투체] : 캐릭터문장(프로필, "질문모름", {}) };
  }

  if(컨디션 || 일정){
    return { 종류:"상태", 음식:[], 컨디션, 일정,
             답: 캐릭터문장(프로필, 일정==="야근" ? "상태야근" : "상태일반", {}) };
  }

  // 야근/약속을 "아니다·없다·끝났다·안 해"로 말한 경우 — "먹은 거면 다시 적어줄래?" 대신 자연스럽게
  if(글.includes("야근") || 글.includes("약속")){
    return { 종류:"상태", 음식:[], 컨디션, 일정,
             답: 캐릭터문장(프로필, "일정없음", {}) };
  }

  return { 종류:"기타", 음식:[], 컨디션, 일정,
           답: 캐릭터문장(프로필, "모름", {글:글}) };
}


