// 자주 나올 질문과 답 — A가 15개까지 늘립니다.
const 준비된답 = [
  { 키워드:["야근","늦게"],      답:"야근이면 운동은 접자. 저녁만 단백질 챙기면 돼." },
  { 키워드:["운동","뭐 하","헬스"], 답:"오늘은 10분만 걷는 걸로 하자. 짧아도 매일이 중요해." },
  { 키워드:["단백질"],           답:"닭가슴살, 계란, 두부, 그릭요거트가 제일 쉬워." },
  { 키워드:["야식","밤에","치킨"], 답:"먹고 싶으면 먹되 국물이나 튀김옷은 좀 남기자." },
  { 키워드:["술","소주","맥주"],   답:"술은 칼로리가 은근 높아. 안주를 단백질로 고르면 좀 나아." },
  { 키워드:["피곤","힘들","졸려"], 답:"피곤하면 무리하지 말자. 오늘은 잘 먹는 것만 신경 써." },
  { 키워드:["살","체중","몸무게"], 답:"하루하루 숫자보다 이번 주에 몇 번 지켰는지가 더 중요해." },
];

function 규칙으로답하기(글, 프로필, 오늘){
  // 컨디션 · 일정
  const 컨디션 = ["좋음","보통","피곤"].find(v => 글.includes(v)) || null;
  const 일정   = 글.includes("야근") ? "야근"
               : 글.includes("약속") ? "약속"
               : 글.includes("평범") ? "평범" : null;

  // 음식
  const 음식 = 음식찾기(글);
  if(음식){
    return { 종류:"음식", 음식:[{이름:음식.이름, kcal:음식.kcal, 단백질:음식.단백질}],
             컨디션, 일정,
             답: 문장만들기(프로필.말투, "기록", {메뉴:음식.이름, kcal:음식.kcal}) };
  }

  // 질문
  if(글.includes("?") || 글.includes("뭐") || 글.includes("어때") || 글.includes("할까")){
    const 찾은 = 준비된답.find(q => q.키워드.some(k => 글.includes(k)));
    return { 종류:"질문", 음식:[], 컨디션, 일정,
             답: 찾은 ? 찾은.답 : "그건 아직 내가 잘 몰라. 먹은 것부터 적어볼까?" };
  }

  // 상태만 바뀐 경우
  if(컨디션 || 일정){
    return { 종류:"상태", 음식:[], 컨디션, 일정,
             답: 일정==="야근" ? "야근이구나. 오늘 운동은 접고 저녁만 챙기자."
                              : "알겠어. 그렇게 잡아둘게." };
  }

  // 못 알아들음 — 추정해서 기록
  return { 종류:"음식", 음식:[{이름:글, kcal:400, 단백질:10}], 컨디션, 일정,
           답:`"${글}"로 적어뒀어. 음식표에 없어서 대략으로 잡았어.` };
}


/* ─────────── 6. 말투별 고정 문장 ─────────── */

// 한국어 조사 — 받침에 따라 골라 붙입니다.
//   조사("제육덮밥","으로","로") → "제육덮밥으로"
//   조사("커피","으로","로")     → "커피로"
// A가 새 문장을 쓸 때 "{메뉴}로", "{메뉴}을" 처럼 조사가 붙는 자리는
// 이 함수를 쓰거나, 아예 조사가 안 붙는 문장으로 쓰세요.
function 조사(단어, 받침있을때, 받침없을때){
  const 글 = String(단어);
  const 끝 = 글.charCodeAt(글.length - 1);
  if(끝 < 0xAC00 || 끝 > 0xD7A3) return 글 + 받침없을때;      // 한글이 아니면
  const 종성 = (끝 - 0xAC00) % 28;
  if(종성 === 8 && 받침있을때 === "으로") return 글 + "로";    // ㄹ 받침은 "로"
  return 글 + (종성 ? 받침있을때 : 받침없을때);
}

const 문장틀 = {
  엄마: {
    첫인사: "안녕! 오늘 컨디션 어때? 먹은 거 있으면 그냥 편하게 적어줘.",
    기록:   "{메뉴} 기록했어. 대략 {kcal}kcal.",
    정리:   "오늘 {먹은칼로리}kcal 먹었어. {부족}\n내일은 딱 하나만 — {할일}",
    부족:   "단백질이 {g}g 모자라. 이 근처에서 채울 수 있어."
  },
  스파르타: {
    첫인사: "시작한다. 오늘 컨디션이랑 먹은 거 적어라.",
    기록:   "{메뉴}. {kcal}kcal 기록했다.",
    정리:   "오늘 {먹은칼로리}kcal. {부족}\n내일 할 일 하나 — {할일}",
    부족:   "단백질 {g}g 부족. 근처에서 채워라."
  }
};

function 문장만들기(말투, 키, 값들){
  const 묶음 = 문장틀[말투] || 문장틀.엄마;
  let 글 = 묶음[키] || "";
  for(const k in 값들) 글 = 글.split("{" + k + "}").join(값들[k]);
  return 글;
}
