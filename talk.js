// 의도가 있으면 찾을 음식명을 돌려주고(대명사뿐이면 ""), 아니면 null.
// ※ 실제 async 호출(음식으로가게찾기)과 카드 렌더는 index.html에서. talk.js는 동기라 직접 못 부름.
function 가게찾기의도(글){
  const 트리거 = ["먹고 싶","먹을래","먹을까","먹으려","어디서","어디 가","어디 파","뭐 먹지","파는","사러"];
  if(!트리거.some(t => 글.includes(t))) return null;
  let s = 글;
  ["이거","그거","저거","이걸","그걸","오늘","지금","진짜","완전","좀"].forEach(w => s = s.split(w).join(" "));
  ["먹고 싶은데","먹고 싶어","먹고 싶다","먹고 싶","먹을래","먹을까","먹으려고","먹으려",
   "어디서 먹지","어디서 파","어디서","어디 가지","어디 가","뭐 먹지","파는 곳","파는데","파는",
   "사러","사고 싶","가지","가야","?","!",".",","].forEach(w => s = s.split(w).join(" "));
  s = s.replace(/\s+/g, " ").trim();
  s = s.replace(/(은|는|이|가|을|를|이나|나)$/, "").trim();
  return s;  // 음식명 (대명사만 있어 못 뽑으면 "")
}

