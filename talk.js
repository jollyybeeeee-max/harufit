function 문장만들기(말투, 키, 값들){
  const 묶음 = 문장틀[말투] || 문장틀.반말;   // 말투 = "반말" 또는 "존댓말"
  let 글 = 묶음[키] || "";
  for(const k in 값들) 글 = 글.split("{" + k + "}").join(값들[k]);
  return 글;
}

// 캐릭터 전용 폴백 문장을 골라준다 (없으면 공용 문장틀로 자동 대체)
// index.html이 첫인사·간식 문장을 캐릭터별로 쓰려면 이 함수를 호출: 캐릭터문장(프로필, "첫인사", {})
function 캐릭터문장(프로필, 키, 값들){
  const 말투체 = (프로필.말투체 === "존댓말") ? "존댓말" : "반말";
  const 캐릭터 = 프로필.캐릭터 || "다정";
  const 전용 = 캐릭터폴백[캐릭터] && 캐릭터폴백[캐릭터][말투체] && 캐릭터폴백[캐릭터][말투체][키];
  const 공용 = 문장틀[말투체] && 문장틀[말투체][키];
  let 글 = 전용 || 공용 || "";
  for(const k in 값들) 글 = 글.split("{" + k + "}").join(값들[k]);
  return 글;
}
