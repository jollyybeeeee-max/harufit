/* ─────────── 1. 입력 검사 ─────────── ★ AI를 부르기 전에 먼저 막는다
   증상 · 질병 · 약 이야기는 AI에게 보내지도 않습니다.
   보내면 AI가 뭐라도 답하려 하고, 그게 의료 조언이 됩니다. */

const 위험한말 = [
  "어지럽","가슴이 답답","토할","토했","숨이 차","쓰러","의식",
  "굶었","안 먹었","먹고 토","살 빼려고 굶","폭식",
  "우울","죽고 싶","살기 싫"
];

const 의료질문 = [
  "약","영양제","보충제","처방","진단","병원","의사","치료",
  "당뇨","고혈압","갑상선","위염","역류","콜레스테롤","호르몬",
  "임신","수유","알레르기 있는데 먹어도","먹어도 되나요","괜찮을까요"
];

function 입력검사(글){
  if(위험한말.some(w => 글.includes(w))){
    return { 막힘:true, 답:
      "그건 앱이 답할 일이 아니야. 몸이 이상하면 병원에 꼭 가봐.\n오늘은 코칭 안 할게." };
  }
  if(의료질문.some(w => 글.includes(w))){
    return { 막힘:true, 답:
      "약이나 병에 관한 건 내가 답할 수 없어. 꼭 전문가한테 물어봐.\n대신 운동이나 음식, 오늘 컨디션 얘기는 얼마든지 도와줄게." };
  }
  return { 막힘:false };
}


/* ─────────── 2. 출력 검사 ─────────── ★ AI가 답한 뒤에도 한 번 더
   AI가 규칙을 어기고 의료 조언을 하거나 혼내는 말을 하면 여기서 걸립니다. */

const 나오면안되는말 = [
  "영양제","보충제","약을","처방","진단","치료","병이","질환",
  "굶어","단식","절식","금식",
  "게으르","한심","실패","의지가 약","또 그러네","겨우","밖에 안"
];

function 출력검사(글){
  const 걸린것 = 나오면안되는말.find(w => 글.includes(w));
  if(걸린것){
    console.warn("출력 검사에 걸렸습니다:", 걸린것);
    return { 막힘:true, 답:
      "음… 지금은 답하기 어려운 얘기야. 오늘 먹은 것부터 적어볼까?" };
  }
  return { 막힘:false, 답:글 };
}


/* ─────────── 3. 안전 검사 ─────────── ★ 이 앱에서 가장 중요한 함수
   못 먹는 것이 든 메뉴를 추천 후보에서 빼냅니다.
   "들어간것"이 안 적힌 메뉴는 아예 추천하지 않습니다 — 모르면 추천 안 함. */

function 안전검사(후보들, 못먹는것){
  return 후보들.filter(후보 => {
    if(!후보.들어간것) return false;
    return !후보.들어간것.some(재료 => 못먹는것.includes(재료));
  });
}


